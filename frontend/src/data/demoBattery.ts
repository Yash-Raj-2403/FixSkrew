import type { BatteryDataset, MeasurementKey, Reading } from "../lib/battery";

/**
 * SIMULATED DEMO DATA. Generated locally from a fixed formula so the dashboard can be
 * previewed without a vehicle or documents. None of these values were measured on any
 * vehicle, and they must never be used for diagnosis. The UI labels this dataset as
 * simulated wherever it appears.
 */
export function demoDataset(): BatteryDataset {
  const hours = 72;
  const end = Date.UTC(2026, 0, 15, 12, 0, 0); // fixed, so the demo never changes
  const readings: Reading[] = [];
  let seed = 7;
  const rand = () => ((seed = (seed * 16807) % 2147483647) / 2147483647 - 0.5);

  for (let h = 0; h <= hours; h++) {
    const t = end - (hours - h) * 3600_000;
    const timestamp = new Date(t).toISOString();
    // Two simulated drive-and-charge cycles per day.
    const phase = (h % 12) / 12;
    const soc = phase < 0.65 ? 92 - phase * 95 : 30 + (phase - 0.65) * 170;
    const add = (key: MeasurementKey, label: string, value: number, unit: string) =>
      readings.push({ key, label, value: Math.round(value * 1000) / 1000, unit, timestamp, groupId: timestamp, sourceName: "Simulated demo data" });

    add("soc", "State of charge", Math.min(100, Math.max(5, soc)), "%");
    add("pack_voltage", "Pack voltage", 690 + soc * 1.35 + rand() * 2, "V");
    add("battery_temp", "Battery temperature", 24 + (phase < 0.65 ? phase * 7 : 6 - (phase - 0.65) * 8) + rand(), "°C");
    const cellMid = 3.35 + soc * 0.0065;
    const spread = 0.012 + Math.abs(rand()) * 0.008;
    add("cell_voltage_max", "Highest cell voltage", cellMid + spread / 2, "V");
    add("cell_voltage_min", "Lowest cell voltage", cellMid - spread / 2, "V");
  }
  // State of health is reported once, not as a history. Pack current is not reported at all,
  // so the dashboard's "not reported" handling is visible in the demo.
  readings.push({ key: "soh", label: "State of health", value: 97, unit: "%", timestamp: new Date(end).toISOString(), groupId: "soh", sourceName: "Simulated demo data" });

  return {
    source: "demo",
    sourceLabel: "Simulated demo data",
    sourceDetail: "Generated by the application to preview this dashboard. Not measured on any vehicle and not usable for diagnosis.",
    vehicle: { label: "Hyundai IONIQ 5 (simulated)", known: true },
    readings,
    dtcs: [{ code: "P0000", description: "Placeholder entry to preview the layout. Not a real fault code.", sourceName: "Simulated demo data" }],
    fetchedAt: new Date(end).toISOString(),
  };
}
